// Bundles the editable JSON in /content into app/data/content.js so the app
// can load it with a plain <script> tag (works offline, even from file://).
//
// Sources of truth (V1.6 curriculum + map; V1.5 encounter pack):
//   black_folk_v1_6_master_curriculum_art_design.json  50 nodes, 10 threads, 8 debates, 14 deepening cards
//   black_folk_v1_5_encounter_pack.json                50 DISCOVER + 80 encounters, starter + bridge sessions
//   black_folk_v1_6_knowledge_map_art_design.json      graph edges + the verified WORDS quote bank
//   v1_6_art_design_encounters.json                    DISCOVER + one interaction per new art/design card
// (V1.5 curriculum and map are kept in content/archive/ for reference only.)
// Editorial layers (no new claims):
//   links.json               thread steps / debate sides wiring onto node ids
//   v1_5_interactions.json   HOW each encounter is played (binary, sort, pick, recall…)
//   understanding_checks.json YOUR WORDS prompt types (explain / reflective) + pilot checks
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(join(root, 'content', f), 'utf8'));

const map = read('black_folk_v1_6_knowledge_map_art_design.json');
const bundle = {
  curriculum: read('black_folk_v1_6_master_curriculum_art_design.json'),
  playtest: read('black_folk_v1_5_encounter_pack.json'),
  knowledgeMap: map,
  links: read('links.json'),
  interactions: read('v1_5_interactions.json'),
  artDesign: read('v1_6_art_design_encounters.json'),
  understanding: read('understanding_checks.json'),
  wordsSource: 'black_folk_v1_6_knowledge_map_art_design.json',
};

const out = join(root, 'app', 'data', 'content.js');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  '// GENERATED by scripts/build-data.mjs from /content. Do not edit by hand.\n' +
    'globalThis.BF_CONTENT = ' + JSON.stringify(bundle) + ';\n'
);
console.log(`content bundled → app/data/content.js (${bundle.curriculum.playable_nodes.length} core nodes, ${bundle.curriculum.deepening_cards.length} deepening cards, ${bundle.playtest.discovery_cards.length + bundle.playtest.encounters.length + bundle.artDesign.discovery_cards.length + bundle.artDesign.encounters.length} playable items)`);
